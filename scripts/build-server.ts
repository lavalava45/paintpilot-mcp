import fs from 'node:fs';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { DEPLOYMENT_ROOT, DEPLOYMENT_MANIFEST, UXP_DEPLOYMENT_FILE, captureBuildInputs, captureBuildOutputs,
  createBuildManifest } from '../src/core/deployment-health.js';

const root = path.resolve(DEPLOYMENT_ROOT);
const destination = path.join(root, 'dist');
const stage = path.join(root, `.tmp-server-build-${randomUUID()}`);
const previous = path.join(root, `.tmp-server-previous-${randomUUID()}`);
const lock = path.join(root, '.tmp-server-build.lock');
// Verify absolute mutation targets before any recursive cleanup or directory move.
for (const target of [destination, stage, previous]) {
  if (path.dirname(path.resolve(target)) !== root
    || !/^(?:dist|\.tmp-server-(?:build|previous)-[0-9a-f-]+)$/.test(path.basename(target)))
    throw new Error(`Unsafe build target: ${target}`);
}
let acquired = false;
let exitCode = 1;
try {
  // One publisher; source edits remain allowed but invalidate the candidate below.
  const fd = fs.openSync(lock, 'wx'); acquired = true;
  fs.writeFileSync(fd, JSON.stringify({ pid: process.pid, at: new Date().toISOString() })); fs.closeSync(fd);
  const before = captureBuildInputs(root);
  if (before.expected_uxp_revision !== before.uxp_source_revision)
    throw new Error('deployment_source_revision_mismatch: server and uxp-plugin/main.js must declare the same bridge revision before building');
  fs.mkdirSync(stage);
  const compiled = spawnSync(process.execPath, [path.join(root, 'node_modules/typescript/bin/tsc'), '--outDir', stage],
    { cwd: root, stdio: 'inherit' });
  if (compiled.error || compiled.status !== 0) throw new Error(`TypeScript build failed (${compiled.error?.message ?? compiled.status})`);
  const after = captureBuildInputs(root);
  if (before.source_sha256 !== after.source_sha256 || before.uxp_sha256 !== after.uxp_sha256)
    throw new Error('deployment_sources_changed_during_build: candidate discarded; wait for concurrent edits to finish and rebuild');
  const manifest = createBuildManifest(after, captureBuildOutputs(stage));
  fs.writeFileSync(path.join(stage, DEPLOYMENT_MANIFEST), `${JSON.stringify(manifest, null, 2)}\n`);
  const marker = path.join(root, UXP_DEPLOYMENT_FILE);
  const oldMarker = fs.existsSync(marker) ? fs.readFileSync(marker) : undefined;
  fs.writeFileSync(`${marker}.tmp`, `// Generated by build:server; captured once when UXP loads.\nmodule.exports = { source_sha256: '${manifest.uxp_sha256}' };\n`);
  fs.renameSync(`${marker}.tmp`, marker);
  const hadPrevious = fs.existsSync(destination);
  let movedPrevious = false;
  try {
    if (hadPrevious) { fs.renameSync(destination, previous); movedPrevious = true; }
    fs.renameSync(stage, destination);
  } catch (error) {
    if (movedPrevious) fs.renameSync(previous, destination);
    if (oldMarker) fs.writeFileSync(marker, oldMarker); else fs.unlinkSync(marker);
    throw error;
  }
  if (hadPrevious) fs.rmSync(previous, { recursive: true, force: true });
  console.error(`[build-server] Published ${manifest.build_id.slice(0, 12)}; bridge ${manifest.expected_uxp_revision}.`);
  console.error('[build-server] Running components were not restarted. Next: restart the selected PaintPilot MCP connection -> reload UXP if changed -> npm run deployment:health.');
  exitCode = 0;
} catch (error) {
  const detail = (error as NodeJS.ErrnoException)?.code === 'EEXIST'
    ? `deployment_build_in_progress: ${lock}; wait for its owner to finish. If that process was killed, verify its PID before removing the stale lock.`
    : error instanceof Error ? error.message : String(error);
  console.error(`[build-server] ${detail}`);
} finally {
  // All recursive targets are fixed children of this checkout created by this invocation.
  if (fs.existsSync(stage)) fs.rmSync(stage, { recursive: true, force: true });
  if (acquired) fs.unlinkSync(lock);
}
process.exitCode = exitCode;
